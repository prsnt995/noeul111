-- Backfill any colors already used by products so they become reusable too.
insert into app.colors (name_ko, name_en, hex)
select distinct color, color, coalesce(swatch, '')
from app.product_variants
on conflict (name_ko, name_en, hex) do nothing;

-- Grants + RLS for the API role (mirrors core migration).
grant select, insert, update, delete on app.colors to noeul_api;
grant usage, select on sequence app.colors_id_seq to noeul_api;
alter table app.colors enable row level security;
do $$ begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'app' and tablename = 'colors' and policyname = 'backend_access'
  ) then
    create policy backend_access on app.colors to noeul_api using (true) with check (true);
  end if;
end $$;