-- Reusable color palette for the admin product flow.
-- Colors were previously only stored denormalised on product_variants(color, swatch),
-- so a custom color created while adding one product could not be reused elsewhere.
-- This table is the canonical palette; variants keep their own color/swatch strings
-- for backward compatibility and the storefront contract is unchanged.
create table if not exists app.colors (
  id bigint generated by default as identity primary key,
  name_ko text not null,
  name_en text not null default '',
  hex text not null default '',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (name_ko, name_en, hex)
);

